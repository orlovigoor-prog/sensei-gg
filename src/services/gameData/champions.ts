export const championCatalog: ChampionCatalogEntry[] = officialChampionReferences.map((champion) => ({
  ...champion,
  assetKey: champion.id
}));

export const normalizeChampionKey = (value: string) => value.trim().toLowerCase().replace(/[^a-z0-9]/g, '');

const championLookup = new Map<string, ChampionCatalogEntry>();

championCatalog.forEach((champion) => {
  [champion.id, champion.name, ...(champion.aliases ?? [])].forEach((value) => {
    championLookup.set(normalizeChampionKey(value), champion);
  });
});

export const getChampionCatalogEntry = (championName: string) => championLookup.get(normalizeChampionKey(championName));

export const getChampionAssetKey = (championName: string) => (
  getChampionCatalogEntry(championName)?.assetKey ?? championName.replace(/[^A-Za-z0-9]/g, '')
);

export const getChampionIconUrl = (championName: string) => (
  getDataDragonAssetUrl(`champion/${getChampionAssetKey(championName)}.png`)
);
